class Personaje {
  final int id;
  final String name;
  final String status;
  final String image;
  final String species;
  final String gender;
  final String origin;
  final String location;

  Personaje({
    required this.id,
    required this.name,
    required this.status,
    required this.image,
    required this.species,
    required this.gender,
    required this.origin,
    required this.location,
  });
}
